	function setAttachment($composer, id, url) {
		url = normalizeGiphyImageUrl(url);
		if (!isValidGiphyImage(id, url)) {
			return;
		}
		ensureHiddenField($composer, 'sreda_giphy_id', id);
		ensureHiddenField($composer, 'sreda_giphy_url', url);

		/* Keep the first version to one visual attachment per post. */
		$composer.find('#ossn-wall-photo input[type="file"]').val('');
		$composer.find('#ossn-wall-photo').hide();

		var $preview = $composer.find('.sreda-giphy-wall-preview');
		if (!$preview.length) {
			$preview = $('<div>', {
				'class': 'sreda-giphy-wall-preview',
				'role': 'status',
			});
			$preview.append($('<img>', {alt: labels.preview}));
			$preview.append($('<button>', {
				type: 'button',
				'class': 'sreda-giphy-wall-preview-remove',
			}).text(labels.remove));
			$preview.insertAfter($composer.find('.controls'));
		}
		$preview.removeAttr('hidden').find('img').attr('src', url);
	}

