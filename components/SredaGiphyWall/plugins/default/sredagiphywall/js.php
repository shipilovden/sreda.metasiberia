	function positionPicker($composer, $picker) {
		var control = $composer.find('.sreda-giphy-wall-control')[0];
		if (!control) {
			return;
		}
		var rect = control.getBoundingClientRect();
		var viewport = window.visualViewport || null;
		var viewportWidth = viewport ? viewport.width : window.innerWidth;
		var viewportHeight = viewport ? viewport.height : window.innerHeight;
		var padding = 8;
		var width = Math.min(360, Math.max(0, viewportWidth - padding * 2));
		$picker.css({
			position: 'fixed',
			width: width + 'px',
			left: '0px',
			top: '0px',
		});

		var height = $picker.outerHeight();
		var top = rect.bottom + 6;
		if (top + height > viewportHeight - padding) {
			top = rect.top - height - 6;
		}
		top = Math.max(padding, Math.min(top, viewportHeight - height - padding));

		var left = rect.left + (rect.width / 2) - (width / 2);
		left = Math.max(padding, Math.min(left, viewportWidth - width - padding));
		$picker.css({left: left + 'px', top: top + 'px'});
	}

