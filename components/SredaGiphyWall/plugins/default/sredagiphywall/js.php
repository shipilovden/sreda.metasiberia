	function isValidLinkPreviewUrl(url) {
		url = String(url || '').trim();
		if (!/^https?:\/\/[^\s]+$/i.test(url)) {
			return false;
		}
		var link = document.createElement('a');
		link.href = url;
		return /^https?:$/i.test(link.protocol) && !!link.hostname;
	}

