		}
	});

	$(document).on('click', '.sreda-link-preview-panel', function (event) {
		event.stopPropagation();
	});

	$(document).on('click', '.sreda-link-preview-close', function () {
		closeLinkPanel($(this).closest('.sreda-link-preview-panel'));
	});

	$(document).on('click', '.sreda-link-preview-submit', function () {
		loadLinkPreview($(this).closest('.sreda-link-preview-panel'));
	});

	$(document).on('keydown', '.sreda-link-preview-input', function (event) {
		if (event.key === 'Enter') {
			event.preventDefault();
			loadLinkPreview($(this).closest('.sreda-link-preview-panel'));
		}
	});

	$(document).on('input paste', '.sreda-link-preview-input', function () {
		var $input = $(this);
		var $panel = $input.closest('.sreda-link-preview-panel');
		var $composer = getComposer(this);
		var value = String($input.val() || '').trim();
		var selectedUrl = String($composer.find('input[name="sreda_link_preview_url"]').val() || '').trim();
		if (selectedUrl && selectedUrl !== value) {
			clearLinkPreview($composer, false);
		}
		clearTimeout($panel.data('sreda-link-preview-delay'));
		if (!value || !isValidLinkPreviewUrl(value)) {
			if (!value) {
				clearLinkPreview($composer, false);
			}
			return;
		}
		var delay = setTimeout(function () {
			loadLinkPreview($panel);
		}, 450);
		$panel.data('sreda-link-preview-delay', delay);
	});

	$(document).on('click', '.sreda-link-preview-selection-remove', function () {
		clearLinkPreview(getComposer(this), true);
	});

	$(document).on('click', '.sreda-giphy-wall-control', function (event) {
		event.preventDefault();
		event.stopPropagation();
		var $composer = getComposer(this);
		var $picker = createPicker($composer);
		var open = !$picker.hasClass('is-open');
		closeAllPickers($picker);
		if (open) {
			$picker.addClass('is-open').removeAttr('hidden');
			positionPicker($composer, $picker);
			if (!$picker.data('sreda-giphy-loaded')) {
				$picker.data('sreda-giphy-loaded', true);
				startGiphySearch($picker, '');
			}
		}
	});

