	$(document).on('click', '.ossn-wall-photo', function () {
		clearAttachment(getComposer(this));
	});

	/* OSSN rejects an empty wall post. A GIF-only post is still a valid post,
	 * so provide an invisible marker before OssnWall extracts the editor text.
	 * The core wall handler runs from <body>; a direct button handler runs first. */
	$(function () {
		var $wallForm = $('#ossn-wall-form');
		if (!$wallForm.length) {
			return;
		}
		var ensureAttachmentPostText = function () {
			var $form = $(this).closest('form');
			var $attachment = $form.find('input[name="sreda_giphy_url"], input[name="sreda_link_preview_url"]').filter(function () {
				return String($(this).val() || '').trim() !== '';
			}).first();
			if (!$attachment.length) {
				return;
			}
			var $editor = $form.find('.ossn-wall-textarea').first();
			if ($editor.length && $editor.text().trim() === '' && !$editor.find('img').length) {
				/* U+200B survives JavaScript/PHP trim but has no visual output. */
				$editor.text('\u200B');
			}
		};
		$wallForm.find('.ossn-wall-post').on('click.sredaGiphyWall', ensureAttachmentPostText);
		$wallForm.on('submit.sredaGiphyWall', function () {
			var $form = $(this);
			var $attachment = $form.find('input[name="sreda_giphy_url"], input[name="sreda_link_preview_url"]').filter(function () {
				return String($(this).val() || '').trim() !== '';
			}).first();
			if (!$attachment.length) {
				return;
			}
			var $post = $form.find('textarea[name="post"]').first();
			if (!$post.length) {
				$post = $('<textarea>', {name: 'post', style: 'display:none;'}).appendTo($form);
			}
			if (String($post.val() || '').trim() === '') {
				$post.val(' ');
			}
		});
	});

	$(document).on('click', function (event) {
		/* The picker button and the picker itself must not be closed by this
		 * document-level outside-click handler in the same event cycle. */
		if ($(event.target).closest('.sreda-giphy-wall-control, .sreda-giphy-wall-picker, .sreda-link-preview-control, .sreda-link-preview-panel').length) {
			return;
		}
		closeAllPickers();
		closeAllLinkPanels();
	});

	$(window).on('resize orientationchange scroll', function () {
		$('.sreda-giphy-wall-picker.is-open').each(function () {
			positionPicker(getComposer(this), $(this));
		});
	});

	if (window.visualViewport) {
		$(window.visualViewport).on('resize scroll', function () {
			$('.sreda-giphy-wall-picker.is-open').each(function () {
				positionPicker(getComposer(this), $(this));
			});
		});
	}

	/* OssnWall clears its composer after a successful wall action. */
	$(document).ajaxSuccess(function (event, xhr, settings, data) {
		var url = settings && settings.url ? settings.url : '';
		if (url.indexOf('action/wall/post') === -1 || !data || !data.success) {
			return;
		}
		$('.ossn-wall-container-data').each(function () {
			clearAttachment($(this));
			clearLinkPreview($(this), true);
		});
	});
})(jQuery);
