	function loadLinkPreview($panel) {
		var $composer = getComposer($panel);
		var url = String($panel.find('.sreda-link-preview-input').val() || '').trim();
		if (!isValidLinkPreviewUrl(url)) {
			clearLinkPreview($composer, false);
			setLinkStatus($panel, labels.linkError, true);
			return;
		}
		var current = $panel.data('sreda-link-preview-xhr');
		if (current && current.readyState !== 4) {
			current.abort();
		}
		clearLinkPreview($composer, false);
		setLinkStatus($panel, labels.linkLoading, false);
		if (!window.Ossn || typeof Ossn.PostRequest !== 'function') {
			setLinkStatus($panel, labels.linkError, true);
			return;
		}
		var request = Ossn.PostRequest({
			url: Ossn.site_url + 'action/sreda/link/preview',
			params: 'url=' + encodeURIComponent(url),
			callback: function (data) {
				if (String($panel.find('.sreda-link-preview-input').val() || '').trim() !== url) {
					return;
				}
				if (typeof data === 'string') {
					try {
						data = JSON.parse(data);
					} catch (error) {
						data = null;
					}
				}
				if (setLinkPreview($composer, data)) {
					setLinkStatus($panel, '', false);
				} else {
					setLinkStatus($panel, labels.linkError, true);
				}
			},
			error: function () {
				if (String($panel.find('.sreda-link-preview-input').val() || '').trim() !== url) {
					return;
				}
				setLinkStatus($panel, labels.linkError, true);
			},
		});
		$panel.data('sreda-link-preview-xhr', request);
	}

