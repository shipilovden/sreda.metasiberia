	function normalizeGiphyImageUrl(url) {
		return String(url || '').trim().replace(/^http:\/\//i, 'https://').split(/[?#]/)[0];
	}

	function isValidGiphyImage(id, url) {
		url = normalizeGiphyImageUrl(url);
		var match = url.match(/^https:\/\/media[0-9]+\.giphy\.com\/media\/([^\/?#\s]{1,128})(?:\/[^?#\s]+)+$/i);
		return /^[^\/?#\s]{1,128}$/.test(id || '')
			&& !!match
			&& String(id).toLowerCase() === match[1].toLowerCase();
	}

	function getGiphyResult(image) {
		var url = normalizeGiphyImageUrl(image && image.thumb);
		var match = url.match(/^https:\/\/media[0-9]+\.giphy\.com\/media\/([^\/?#\s]{1,128})(?:\/[^?#\s]+)+$/i);
		if (!match) {
			return false;
		}
		var id = String(image && image.id || '').trim();
		/* The URL is generated by OssnGiphy. Use its path id if an OSSN/Giphy
		 * version serializes the separate id field differently. */
		if (!isValidGiphyImage(id, url) || id.toLowerCase() !== match[1].toLowerCase()) {
			id = match[1];
		}
		return {id: id, url: url};
	}

	function isSuccessfulGiphyResponse(data) {
		return !!(data && (data.success === true || data.success === 1
			|| data.success === '1' || data.success === 'true'));
	}

